"""Outputs under out/ (frd-trd.md 2.3, 8, 9; backend-ai.md 8).

build(...)                -> report dict (out/report.json, schema_version 2)
pr_body(report, patch)    -> PR_BODY.md text
write(report, patch, out) -> written paths. report.json always;
                             patchpilot.patch and PR_BODY.md only when
                             result.status == "patched" (an unverified patch
                             file is never written, and a stale one is removed).
write_attempt(attempt, out)   -> out/attempts/attempt_N.txt (once per attempt)
write_spec_diff(diff, out)    -> out/spec_diff.json (always)
append_run(out, record)       -> one line in out/runs.jsonl (backend-ai.md 5.5, 5.6)

Exit codes (frd-trd.md 2.2): patched / nothing_to_patch -> 0,
no_verified_patch -> 1, config_error -> 2, api_unavailable -> 3.
No field ever holds the API key.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Iterable, Optional

from patchpilot.models import Attempt, SpecDiff, TestRun, Usage

SCHEMA_VERSION = 2
PATCH_FILE = "patchpilot.patch"
PR_BODY_FILE = "PR_BODY.md"
REPORT_FILE = "report.json"
SPEC_DIFF_FILE = "spec_diff.json"
RUNS_FILE = "runs.jsonl"
ATTEMPTS_DIR = "attempts"

STATUS_EXIT = {
    "patched": 0,
    "nothing_to_patch": 0,
    "no_verified_patch": 1,
    "config_error": 2,
    "api_unavailable": 3,
}
EXIT_STATUS_ON_ERROR = {2: "config_error", 3: "api_unavailable"}

PR_TITLE = "fix(client): migrate to Weather API v2 (current_weather → current)"
STAGED_NOTE = "Note: v2 is a staged spec served by a local proxy."
FOOTER = "Generated by PatchPilot. Tests were not modified."


def exit_code_for(status: str) -> int:
    return STATUS_EXIT[status]


def _rel(out_dir: Path | str, name: str) -> str:
    return (Path(out_dir) / name).as_posix()


def attempt_file(n: int) -> str:
    return f"{ATTEMPTS_DIR}/attempt_{n}.txt"


def _attempt_entry(a: Attempt, out_dir: Path | str) -> dict:
    d: dict = {"n": a.n, "effort": a.effort, "result": a.result}
    if a.result == "rejected":
        d["code"] = a.code
        d["detail"] = a.detail
    else:
        d["files"] = list(a.files)
        d["added"] = a.added
        d["removed"] = a.removed
    d["raw_file"] = _rel(out_dir, attempt_file(a.n))
    return d


def _first_error(run: Optional[TestRun]) -> Optional[str]:
    if run and run.first_error:
        return next(iter(run.first_error.values()))
    return None


def build(*, status: str, out_dir: Path | str = "out",
          base_url: Optional[str] = None, proxy_stage: Optional[str] = None,
          diff: Optional[SpecDiff] = None, usages: Iterable[Usage] = (),
          reproduce: Optional[TestRun] = None, tests_hash_before: Optional[str] = None,
          attempts: Iterable[Attempt] = (), verify: Optional[TestRun] = None,
          tests_hash_after: Optional[str] = None, model: Optional[str] = None,
          pr_url: Optional[str] = None, error_code: Optional[str] = None,
          error_message: Optional[str] = None) -> dict:
    """Report dict per frd-trd.md 8. Extra keys (marked [added] in comments) are additive."""
    if status not in STATUS_EXIT:
        raise ValueError(f"unknown status: {status!r}")
    patched = status == "patched"
    rep: dict = {
        "tool": "patchpilot",
        "schema_version": SCHEMA_VERSION,
        "staged_v2": True,
        "base_url": base_url,
        "proxy_stage": proxy_stage,
        "spec_diff_file": _rel(out_dir, SPEC_DIFF_FILE),
        "changes": [c.id for c in diff.changes] if diff else [],
        "usages": [u.to_dict() for u in usages],
        "reproduce": None,
        "attempts": [_attempt_entry(a, out_dir) for a in attempts],
        "verify": None,
        "result": {
            "exit_code": STATUS_EXIT[status],
            "status": status,
            "patch_file": _rel(out_dir, PATCH_FILE) if patched else None,
            "pr_body_file": _rel(out_dir, PR_BODY_FILE) if patched else None,
            "pr_url": pr_url,
            "model": model,
            "error": ({"code": error_code, "message": error_message}   # [added]
                      if error_code else None),
        },
    }
    if reproduce is not None:
        rep["reproduce"] = {
            "passed": reproduce.passed,
            "failed": reproduce.failed,
            "failed_tests": list(reproduce.failed_tests),
            "tests_hash": tests_hash_before,
            "first_error": _first_error(reproduce),                     # [added]
        }
    if verify is not None:
        rep["verify"] = {
            "passed": verify.passed,
            "failed": verify.failed,
            "tests_hash_before": tests_hash_before,
            "tests_hash_after": tests_hash_after,
            "unchanged": bool(tests_hash_before) and tests_hash_before == tests_hash_after,
        }
    return rep


def _short_hash(h: Optional[str]) -> str:
    if not h:
        return "n/a"
    return h.split(":", 1)[-1][:12]


def _patch_stats(patch_text: str) -> tuple[list[str], int, int]:
    files, added, removed, in_hunk = [], 0, 0, False
    for line in (patch_text or "").split("\n"):
        if line.startswith("diff --git "):
            parts = line.split(" b/", 1)
            if len(parts) == 2:
                files.append(parts[1].strip())
            in_hunk = False
        elif line.startswith("@@"):
            in_hunk = True
        elif in_hunk and line.startswith("+") and not line.startswith("+++"):
            added += 1
        elif in_hunk and line.startswith("-") and not line.startswith("---"):
            removed += 1
    return files, added, removed


def pr_body(report: dict, patch_text: str, diff: Optional[SpecDiff] = None) -> str:
    """PR_BODY.md (frd-trd.md 9). Pass diff for the full Spec changes table;
    without it the table lists change IDs only."""
    rep = report.get("reproduce") or {}
    ver = report.get("verify") or {}
    res = report.get("result") or {}
    attempts = report.get("attempts") or []
    total_before = (rep.get("passed") or 0) + (rep.get("failed") or 0)
    first_error = rep.get("first_error") or "an error"
    files, added, removed = _patch_stats(patch_text)

    lines = [f"# {PR_TITLE}", "", STAGED_NOTE, "", "## Before", "",
             (f"Against the v2 response, the client still read the v1 fields. "
              f"{rep.get('failed', 0)} of {total_before} fixed tests failed "
              f"(first error: `{first_error}`)."),
             "", "## After", "",
             (f"The client reads the v2 fields. The same {ver.get('passed', 0) + ver.get('failed', 0)} "
              f"tests ran unchanged: {ver.get('passed', 0)} passed, {ver.get('failed', 0)} failed."),
             "", "## Spec changes", "", "| id | type | from | to |", "|---|---|---|---|"]
    if diff is not None:
        for c in diff.changes:
            lines.append(f"| {c.id} | {c.type} | `{c.from_}` | `{c.to}` |")
    else:
        for cid in report.get("changes") or []:
            lines.append(f"| {cid} | | | |")

    lines += ["", "## Affected usages", ""]
    usages = report.get("usages") or []
    if usages:
        for u in usages:
            ids = " ".join(u.get("change_ids") or [])
            lines.append(f"- `{u['path']}:{u['line']}` {ids}".rstrip())
    else:
        lines.append("- none found")

    hb, ha = ver.get("tests_hash_before"), ver.get("tests_hash_after")
    lines += [
        "", "## Verification", "",
        f"- pytest before: {rep.get('passed', 0)} passed, {rep.get('failed', 0)} failed",
        f"- pytest after: {ver.get('passed', 0)} passed, {ver.get('failed', 0)} failed",
        (f"- `tests/` hash: {_short_hash(hb)} before, {_short_hash(ha)} after "
         f"({'unchanged' if ver.get('unchanged') else 'CHANGED'})"),
        f"- attempts: {len(attempts)}",
        f"- patch: {', '.join(files) or 'n/a'} (+{added} -{removed})",
        f"- model: {res.get('model') or 'n/a'}",
        "", FOOTER, "",
    ]
    return "\n".join(lines)


def _write_text(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def prepare_out(out_dir: Path | str) -> None:
    """Remove outputs of an earlier run so nothing stale is mistaken for this run.
    Deletes only the files PatchPilot itself writes. Keeps runs.jsonl (model comparison)."""
    out = Path(out_dir)
    for name in (PATCH_FILE, PR_BODY_FILE, REPORT_FILE, SPEC_DIFF_FILE):
        p = out / name
        if p.is_file():
            p.unlink()
    adir = out / ATTEMPTS_DIR
    if adir.is_dir():
        for p in adir.glob("attempt_*.txt"):
            p.unlink()
    out.mkdir(parents=True, exist_ok=True)


def write_spec_diff(diff: SpecDiff, out_dir: Path | str) -> Path:
    return _write_text(Path(out_dir) / SPEC_DIFF_FILE,
                       json.dumps(diff.to_dict(), indent=2, ensure_ascii=False) + "\n")


def write_attempt(attempt: Attempt, out_dir: Path | str, max_attempts: int = 3) -> Path:
    head = [
        f"attempt: {attempt.n}/{max_attempts}",
        f"model: {attempt.model or 'n/a'}",
        f"effort: {attempt.effort}",
        f"stop_reason: {attempt.stop_reason or 'n/a'}",
        f"result: {attempt.result}",
    ]
    if attempt.result == "rejected":
        head.append(f"code: {attempt.code}")
        head.append("detail: " + (attempt.detail or "").replace("\n", "\n        "))
    else:
        head.append(f"files: {', '.join(attempt.files)} (+{attempt.added} -{attempt.removed})")
    body = "\n".join(head) + "\n\n----- raw output -----\n" + (attempt.raw_output or "")
    if not body.endswith("\n"):
        body += "\n"
    if attempt.test_log:
        body += "\n----- pytest output after this attempt -----\n" + attempt.test_log
        if not body.endswith("\n"):
            body += "\n"
    return _write_text(Path(out_dir) / attempt_file(attempt.n), body)


def write(report: dict, patch_text: Optional[str], out_dir: Path | str,
          attempts: Optional[Iterable[Attempt]] = None,
          diff: Optional[SpecDiff] = None) -> list[Path]:
    out = Path(out_dir)
    written: list[Path] = []
    patched = (report.get("result") or {}).get("status") == "patched" and bool(patch_text)
    for name in (PATCH_FILE, PR_BODY_FILE):
        p = out / name
        if not patched and p.is_file():
            p.unlink()                      # never leave an unverified or stale patch behind
    if attempts:
        for a in attempts:
            written.append(write_attempt(a, out))
    if patched:
        text = patch_text if patch_text.endswith("\n") else patch_text + "\n"
        written.append(_write_text(out / PATCH_FILE, text))
        written.append(_write_text(out / PR_BODY_FILE, pr_body(report, text, diff)))
    written.append(_write_text(out / REPORT_FILE,
                               json.dumps(report, indent=2, ensure_ascii=False) + "\n"))
    return written


def next_run_number(out_dir: Path | str) -> int:
    p = Path(out_dir) / RUNS_FILE
    if not p.is_file():
        return 1
    best = 0
    for line in p.read_text(encoding="utf-8").splitlines():
        try:
            best = max(best, int(json.loads(line).get("run", 0)))
        except (ValueError, AttributeError):
            continue
    return best + 1


def append_run(out_dir: Path | str, record: dict) -> Path:
    p = Path(out_dir) / RUNS_FILE
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")
    return p
